#!/usr/bin/env python3
"""
Generate and check the wiki's derived artifacts.

    build.py check     report every inconsistency, change nothing (exit 1 if any)
    build.py write     regenerate glossary + search-index.json, sync category rows,
                       the README key-terms block, and README counts
    build.py report    reverse index for Wiki-Sources col L, and the gap report

Design notes worth keeping:

* The full per-category tables live in glossary/categories.md (moved out of the
  README Sep 2026, so the README shows a few key terms instead of all of them).
  Row ORDER inside a category there is hand-curated and pedagogical (LLMs before
  SLMs before Local LLMs). The generator syncs row CONTENT in place and appends
  new entries at the end of their category. It never reorders.
* The README's Concepts section is a generated block: per category, the terms
  other entries link to most (ties broken by that hand-curated order), plus a
  link to the full category list. Derived, so it cannot go stale.
* The glossary is alphabetical and fully derived, so it is regenerated whole.
* `check` is the mode that runs on every publish. `write` is only for when
  check reports a fixable difference.
"""
